/**
 * The frozen map from every tldraw use in `apps/web/src` (outside `canvas/`) to its Excalidraw-era
 * replacement (docs/EXCALIDRAW-CONTRACTS.md §6 is generated from this file). Wave-3 owners port a file by
 * looking up each `editor.*` member and each imported tldraw symbol here. `contracts.test.ts` scans the
 * source tree: a new `editor.*` member, a new imported tldraw symbol or a new file that uses tldraw
 * without an owner fails the test, as does a target below that the API does not have.
 *
 * Target notation:
 *   canvas:<path>     a LobbyCanvas member (impl.ts LOBBY_CANVAS_MEMBERS; `on:<event>` is an event)
 *   registry:<key>    a FeatureRegistries member (registries.ts)
 *   context:<key>     a CanvasFeatureContext member (feature.ts)
 *   helper:<mod>.<fn> a pure helper exported by canvas/api/<mod>.ts, or `signals.<fn>` (lib/signals.ts)
 *   schema:<mod>.<x>  an export of @draftroom/canvas-schema/<mod>
 *   type:<Name>       a type exported by canvas/api/index.ts
 *   feature:<owner>   no canvas API: the owner's feature code computes it over `items()`
 *   dropped           no replacement (the note says why)
 */
